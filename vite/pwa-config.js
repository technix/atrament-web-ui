import fs from 'node:fs';

// default max size of game zip archive, MB
const DEFAULT_ZIP_MAX_SIZE = 100;

const THEMES_DIR = new URL('../resources/themes/', import.meta.url);
const DEFAULT_THEME = 'light';
const DEFAULT_BG_COLOR = '#FCFCFC';

// background color of the game theme
function getThemeColor(themeName) {
  const themes = {};
  fs.readdirSync(THEMES_DIR)
    .filter((file) => file.endsWith('.json'))
    .forEach((file) => {
      const { name, theme } = JSON.parse(fs.readFileSync(new URL(file, THEMES_DIR), 'utf8'));
      themes[name] = theme;
    });
  const theme = themes[themeName] || themes[DEFAULT_THEME];
  return theme?.['bg-color'] || DEFAULT_BG_COLOR;
}

export default function getPWAConfig(atramentCfg) {
  const themeColor = getThemeColor(atramentCfg.theme);
  let pwaConfig = {
    registerType: 'autoUpdate',
    includeAssets: ['**/!(*.ink)'],
    workbox: {
      globPatterns: [
        '**/*.{js,css,html,woff2}',
        // icons generated by pwaAssets
        '{pwa-,maskable-icon-,apple-touch-icon-}*.png',
        'favicon.{ico,svg}'
      ],
    },
    manifest: {
      name: atramentCfg.name,
      short_name: atramentCfg.short_name,
      description: atramentCfg.description,
      start_url: "./",
      display: "standalone",
      orientation: "portrait",
      background_color: themeColor,
      theme_color: themeColor
    },
    pwaAssets: {
      config: 'vite/pwa-assets.config.js'
    }
  };

  if (atramentCfg.game.zip) {
    const gamePath = atramentCfg.game.path.replace(/^(\.?\/)+|\/+$/g, '');
    // game folder is packed into zip and removed from the build,
    // so exclude its files but keep other public assets
    pwaConfig.includeAssets = [ ...pwaConfig.includeAssets, `!${gamePath}/**` ];
    // precache the zip itself
    pwaConfig.workbox.globPatterns = [ ...pwaConfig.workbox.globPatterns, atramentCfg.game.zip ];
    // generate service worker after zip is created
    pwaConfig.integration = { closeBundleOrder: 'post' };

    // zip size limit (MB)
    const zipMaxSize = Number(atramentCfg.game.zip_max_size) || DEFAULT_ZIP_MAX_SIZE;
    pwaConfig.workbox.maximumFileSizeToCacheInBytes = zipMaxSize * 1024 * 1024;
    // fail the build if the zip too large or missing
    pwaConfig.workbox.manifestTransforms = [
      async (manifest) => {
        if (!manifest.some((entry) => entry.url === atramentCfg.game.zip)) {
          throw new Error(
            `Game archive "${atramentCfg.game.zip}" is not included into service worker precache: ` +
            `it is either missing or larger than ${zipMaxSize} MB. ` +
            'Set "game.zip_max_size" (in MB) in atrament.config.json to change the limit.'
          );
        }
        return { manifest };
      }
    ];
  }

  return pwaConfig;
}
